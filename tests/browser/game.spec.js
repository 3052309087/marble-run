import { test, expect } from '@playwright/test'
import pg from '../../server/node_modules/pg/lib/index.js'
import { mkdir } from 'node:fs/promises'
import { databaseConfig } from '../database-config.mjs'

test('register, play, save, rank, resume, and mobile controls', async ({ page }) => {
  const username = 'ui_' + Date.now()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await mkdir('.artifacts', { recursive: true })
  try {
    await page.goto('/')
    await page.screenshot({ path: '.artifacts/login-desktop.png', fullPage: true })
    await page.getByRole('button', { name: '还没有档案？ 创建一个' }).click()
    await page.getByLabel('用户名').fill(username)
    // WASD in passwords must stay in the input and must not start the hidden game.
    await page.getByLabel('密码', { exact: true }).fill('wasd-secret')
    await page.getByRole('button', { name: '创建并开始' }).click()
    await expect(page.getByRole('heading', { name: '闯关实验室', exact: true })).toBeVisible()
    await expect(page.locator('.level-list button').nth(1)).toBeDisabled()
    await page.screenshot({ path: '.artifacts/game-desktop.png', fullPage: true })
    const firstClear = page.waitForResponse(response => response.url().endsWith('/api/results') && response.request().method() === 'POST')
    await page.getByRole('button', { name: '开始本关' }).click()
    await expect(page.getByRole('button', { name: '暂停', exact: true })).toBeVisible()
    await page.keyboard.down('ArrowRight')
    const saved = await firstClear
    await page.keyboard.up('ArrowRight')
    expect(saved.status()).toBe(201)
    await expect(page.getByRole('button', { name: '挑战下一关' })).toBeEnabled()
    await expect(page.locator('.result-row')).toHaveCount(1)
    await expect(page.locator('.ranking-stat')).toContainText(/#\d+/)
    await page.getByRole('button', { name: '查看全站排名' }).click()
    await expect(page.locator('.leader-row.is-me')).toContainText(username)
    await page.screenshot({ path: '.artifacts/leaderboard-desktop.png', fullPage: true })
    await page.getByRole('button', { name: '闯关实验室', exact: true }).click()
    await page.getByRole('button', { name: '挑战下一关' }).click()
    await expect(page.locator('.game-card-head h2')).toContainText('第 2 关')
    await page.getByRole('button', { name: '开始本关' }).click()
    await expect(page.getByRole('button', { name: '暂停', exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByText('已暂停计时', { exact: true })).toBeVisible()
    const paused = await page.locator('.timer strong').textContent()
    await page.waitForTimeout(250)
    expect(await page.locator('.timer strong').textContent()).toBe(paused)
    await page.getByRole('button', { name: '继续挑战' }).click()
    await page.getByRole('button', { name: '暂停', exact: true }).click()
    await page.reload()
    await expect(page.locator('.game-card-head h2')).toContainText('第 2 关')
    await expect(page.locator('.result-row')).toHaveCount(1)
    await page.setViewportSize({ width: 390, height: 844 })
    await expect(page.getByRole('button', { name: '向右', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: '.artifacts/game-mobile.png', fullPage: true })
    await page.getByRole('button', { name: '全站排行榜', exact: true }).click()
    await expect(page.locator('.personal-rank')).toContainText(/#\d+/)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: '.artifacts/leaderboard-mobile.png', fullPage: true })
    await page.getByRole('button', { name: '退出登录', exact: true }).click()
    await page.getByLabel('用户名').fill(username)
    await page.getByLabel('密码', { exact: true }).fill('wasd-secret')
    await page.getByRole('button', { name: '进入实验室' }).click()
    await expect(page.locator('.game-card-head h2')).toContainText('第 2 关')
    expect(errors).toEqual([])
  } finally {
    const db = new pg.Client(databaseConfig())
    await db.connect()
    await db.query('DELETE FROM users WHERE username = $1',[username])
    await db.end()
  }
})
